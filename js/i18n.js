function getLang() {
  return localStorage.getItem("site-lang") === "en" ? "en" : "ru";
}

function t(key) {
  const lang = getLang();
  return translations[lang][key] || translations.ru[key] || key;
}

function applyLang(lang) {
  localStorage.setItem("site-lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = translations[lang][key] || translations.ru[key];
    if (!value) return;
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = value;
    else el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const attr = el.getAttribute("data-i18n-attr");
    const key = el.getAttribute("data-i18n-key");
    const value = translations[lang][key] || translations.ru[key];
    if (value) el.setAttribute(attr, value);
  });

  const titleKey = document.body.getAttribute("data-title");
  if (titleKey) document.title = t(titleKey);

  document.querySelectorAll("[data-lang-set]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.getAttribute("data-lang-set") === lang));
  });
}

document.addEventListener("click", (event) => {
  const btn = event.target.closest("[data-lang-set]");
  if (!btn) return;
  applyLang(btn.getAttribute("data-lang-set"));
});

applyLang(getLang());
